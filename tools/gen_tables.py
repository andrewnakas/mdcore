#!/usr/bin/env python3
"""Generates src/ym2612_tables.h: the log-sine and exponent ROMs of the OPN2
operator, computed from their closed forms, so the core needs no libm."""
import math
logsin = [round(-math.log2(math.sin((2 * i + 1) * math.pi / 1024)) * 256) for i in range(256)]
exp = [round((2 ** (i / 256) - 1) * 1024) for i in range(256)]
def emit(name, typ, vals):
    rows = [", ".join("%4d" % v for v in vals[i:i + 16]) for i in range(0, len(vals), 16)]
    return "static const %s %s[%d] = {\n    %s\n};\n" % (typ, name, len(vals), ",\n    ".join(rows))
with open("src/ym2612_tables.h", "w") as f:
    f.write("/* Generated by tools/gen_tables.py - do not edit. */\n")
    f.write("/* logsin[i] = round(-log2(sin((2i+1)*pi/1024)) * 256) */\n" + emit("ym_logsin", "u16", logsin))
    f.write("/* exp[i] = round((2^(i/256) - 1) * 1024) */\n" + emit("ym_exp", "u16", exp))
